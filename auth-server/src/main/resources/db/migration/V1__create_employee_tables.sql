-- 사원 계정. 비밀번호는 BCrypt 해시만 저장한다.
CREATE TABLE TB_EMP (
    EMP_ID          VARCHAR(20)  NOT NULL,
    EMP_NM          VARCHAR(50)  NOT NULL,
    DEPT_NM         VARCHAR(50),
    PWD_HASH        VARCHAR(100) NOT NULL,
    USE_YN          BOOLEAN      NOT NULL DEFAULT TRUE,
    LOCK_YN         BOOLEAN      NOT NULL DEFAULT FALSE,
    PWD_CHG_REQ_YN  BOOLEAN      NOT NULL DEFAULT TRUE,
    LOGIN_FAIL_CNT  INTEGER      NOT NULL DEFAULT 0,
    PWD_CHG_DT      TIMESTAMP,
    LAST_LOGIN_DT   TIMESTAMP,
    REG_DT          TIMESTAMP    NOT NULL,
    REG_EMP_ID      VARCHAR(20),
    UPD_DT          TIMESTAMP    NOT NULL,
    UPD_EMP_ID      VARCHAR(20),
    CONSTRAINT PK_EMP PRIMARY KEY (EMP_ID),
    CONSTRAINT CK_EMP_ID CHECK (EMP_ID ~ '^[A-Za-z0-9_.-]{3,20}$'),
    CONSTRAINT CK_EMP_FAIL_CNT CHECK (LOGIN_FAIL_CNT >= 0)
);

-- 사원별 역할. JWT 의 roles 클레임이 된다.
CREATE TABLE TB_EMP_ROLE (
    EMP_ID   VARCHAR(20) NOT NULL,
    ROLE_CD  VARCHAR(20) NOT NULL,
    CONSTRAINT PK_EMP_ROLE PRIMARY KEY (EMP_ID, ROLE_CD),
    CONSTRAINT FK_EMP_ROLE_EMP FOREIGN KEY (EMP_ID) REFERENCES TB_EMP (EMP_ID),
    CONSTRAINT CK_EMP_ROLE_CD CHECK (ROLE_CD IN ('AGENT', 'UNDERWRITER', 'OPERATOR', 'ADMIN'))
);

-- 로그인 시도 이력. 없는 사번으로 시도한 것도 남기므로 사원 테이블을 참조하지 않는다. 추가 전용.
CREATE TABLE TB_LOGIN_HIST (
    HIST_ID    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    EMP_ID     VARCHAR(64) NOT NULL,
    RESULT_CD  VARCHAR(20) NOT NULL,
    CLIENT_IP  VARCHAR(45),
    LOGIN_DT   TIMESTAMP   NOT NULL,
    CONSTRAINT PK_LOGIN_HIST PRIMARY KEY (HIST_ID),
    CONSTRAINT CK_LOGIN_HIST_RESULT CHECK (RESULT_CD IN ('SUCCESS', 'BAD_CREDENTIALS', 'LOCKED', 'DISABLED'))
);

CREATE INDEX IX_LOGIN_HIST_EMP_DT ON TB_LOGIN_HIST (EMP_ID, LOGIN_DT DESC);
CREATE INDEX IX_LOGIN_HIST_DT ON TB_LOGIN_HIST (LOGIN_DT DESC);

-- 사원 관리 감사 이력 (등록, 정보·역할 변경, 사용 여부 변경, 비밀번호 초기화, 잠금 해제). 추가 전용.
CREATE TABLE TB_EMP_AUDIT (
    AUDIT_ID      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    EMP_ID        VARCHAR(20)  NOT NULL,
    ACTION        VARCHAR(20)  NOT NULL,
    DETAIL        VARCHAR(500),
    ACT_EMP_ID    VARCHAR(20),
    GLOBAL_TX_ID  VARCHAR(64),
    ACT_DT        TIMESTAMP    NOT NULL,
    CONSTRAINT PK_EMP_AUDIT PRIMARY KEY (AUDIT_ID),
    CONSTRAINT CK_EMP_AUDIT_ACTION CHECK (ACTION IN ('CREATE', 'UPDATE', 'RESET_PASSWORD', 'UNLOCK', 'CHANGE_PASSWORD'))
);

CREATE INDEX IX_EMP_AUDIT_EMP ON TB_EMP_AUDIT (EMP_ID, AUDIT_ID DESC);
