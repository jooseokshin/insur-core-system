-- auth 스키마의 모든 테이블과 컬럼에 설명(COMMENT)을 단다. DB 도구에서 바로 뜻을 볼 수 있게 하려는 것이고, 동작은 바꾸지 않는다.
-- 앞으로 테이블이나 컬럼을 추가하는 마이그레이션은 같은 파일에 COMMENT 도 함께 쓴다 (SchemaCommentTest 가 빠진 것을 잡는다).

COMMENT ON TABLE TB_EMP IS '사원 계정. 로그인과 역할의 기준';
COMMENT ON COLUMN TB_EMP.EMP_ID IS '사번 (토큰의 sub, 코어의 처리 사번)';
COMMENT ON COLUMN TB_EMP.EMP_NM IS '이름 (토큰의 name)';
COMMENT ON COLUMN TB_EMP.DEPT_NM IS '부서명';
COMMENT ON COLUMN TB_EMP.PWD_HASH IS '비밀번호 BCrypt 해시 (원문은 저장하지 않는다)';
COMMENT ON COLUMN TB_EMP.USE_YN IS '사용 여부. false 면 로그인과 토큰 발급이 거절된다(E-AUTH-103)';
COMMENT ON COLUMN TB_EMP.LOCK_YN IS '잠금 여부. 비밀번호를 연속 5회 틀리면 true, 관리자가 잠금 해제나 비밀번호 초기화로 푼다';
COMMENT ON COLUMN TB_EMP.PWD_CHG_REQ_YN IS '비밀번호 변경 필요 여부 (관리자가 만들거나 초기화한 임시 비밀번호). true 면 변경 전까지 토큰을 받을 수 없다';
COMMENT ON COLUMN TB_EMP.LOGIN_FAIL_CNT IS '연속 로그인 실패 횟수 (성공하면 0)';
COMMENT ON COLUMN TB_EMP.PWD_CHG_DT IS '마지막 비밀번호 변경 일시';
COMMENT ON COLUMN TB_EMP.LAST_LOGIN_DT IS '마지막 로그인 성공 일시';
COMMENT ON COLUMN TB_EMP.REG_DT IS '등록 일시';
COMMENT ON COLUMN TB_EMP.REG_EMP_ID IS '등록한 사번 (초기 관리자·개발 계정은 SYSTEM)';
COMMENT ON COLUMN TB_EMP.UPD_DT IS '마지막 수정 일시';
COMMENT ON COLUMN TB_EMP.UPD_EMP_ID IS '마지막으로 수정한 사번';

COMMENT ON TABLE TB_EMP_ROLE IS '사원별 업무 역할 (토큰의 roles 클레임). 바꾸면 다음 토큰부터 반영';
COMMENT ON COLUMN TB_EMP_ROLE.EMP_ID IS '사번 (TB_EMP)';
COMMENT ON COLUMN TB_EMP_ROLE.ROLE_CD IS '역할 (AGENT:설계사, UNDERWRITER:심사, OPERATOR:계약관리, CLAIM:보상, ADMIN:관리자)';

COMMENT ON TABLE TB_EMP_AUDIT IS '사원 계정 변경 감사 이력 (추가만 함)';
COMMENT ON COLUMN TB_EMP_AUDIT.AUDIT_ID IS '감사 일련번호';
COMMENT ON COLUMN TB_EMP_AUDIT.EMP_ID IS '대상 사번';
COMMENT ON COLUMN TB_EMP_AUDIT.ACTION IS '동작 (CREATE, UPDATE, RESET_PASSWORD, UNLOCK, CHANGE_PASSWORD)';
COMMENT ON COLUMN TB_EMP_AUDIT.DETAIL IS '변경 내용 (예: 역할 [AGENT]→[UNDERWRITER])';
COMMENT ON COLUMN TB_EMP_AUDIT.ACT_EMP_ID IS '처리한 사번 (본인 비밀번호 변경은 본인)';
COMMENT ON COLUMN TB_EMP_AUDIT.GLOBAL_TX_ID IS '거래 UUID';
COMMENT ON COLUMN TB_EMP_AUDIT.ACT_DT IS '처리 일시';

COMMENT ON TABLE TB_LOGIN_HIST IS '로그인 시도 이력 (성공·실패 모두, 추가만 함)';
COMMENT ON COLUMN TB_LOGIN_HIST.HIST_ID IS '이력 일련번호';
COMMENT ON COLUMN TB_LOGIN_HIST.EMP_ID IS '입력한 사번 (없는 사번도 그대로 남긴다)';
COMMENT ON COLUMN TB_LOGIN_HIST.RESULT_CD IS '결과 (SUCCESS, BAD_CREDENTIALS:사번·비밀번호 불일치, LOCKED:잠긴 계정, DISABLED:사용 중지)';
COMMENT ON COLUMN TB_LOGIN_HIST.CLIENT_IP IS '접속 IP (프록시 뒤에서는 X-Forwarded-For 의 원래 주소)';
COMMENT ON COLUMN TB_LOGIN_HIST.LOGIN_DT IS '시도 일시';

