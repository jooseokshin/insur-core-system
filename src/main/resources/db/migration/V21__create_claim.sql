-- 보상(사고 접수와 보험금 지급).
-- 상태: 10 접수 → 20 손해사정 완료(지급 대기) → 40 지급 완료, 10·20 → 80 면책(부지급), 10 → 90 접수 취소
CREATE TABLE TB_CLM (
    CLM_NO           VARCHAR(30)    NOT NULL,
    CONTRACT_NO      VARCHAR(30)    NOT NULL,
    CLM_STAT_CD      VARCHAR(2)     NOT NULL,
    ACDT_DT          DATE           NOT NULL,
    ACDT_DESC        VARCHAR(500)   NOT NULL,
    CLAIMANT_ID      VARCHAR(20)    NOT NULL,
    TOTAL_CLAIM_AMT  NUMERIC(15, 0) NOT NULL,
    TOTAL_PAY_AMT    NUMERIC(15, 0),
    RPT_DT           TIMESTAMP      NOT NULL,
    RPT_EMP_ID       VARCHAR(64),
    ADJ_EMP_ID       VARCHAR(64),
    ADJ_DT           TIMESTAMP,
    DECIDE_EMP_ID    VARCHAR(64),
    DECIDE_DT        TIMESTAMP,
    DECIDE_MEMO      VARCHAR(500),
    GLOBAL_TX_ID     VARCHAR(64)    NOT NULL,
    REQ_HASH         VARCHAR(64)    NOT NULL,
    CONSTRAINT PK_CLM PRIMARY KEY (CLM_NO),
    CONSTRAINT FK_CLM_CONTRACT FOREIGN KEY (CONTRACT_NO) REFERENCES TB_CTR_LGD (CONTRACT_NO),
    CONSTRAINT UK_CLM_GLOBAL_TX_ID UNIQUE (GLOBAL_TX_ID),
    CONSTRAINT CK_CLM_STAT CHECK (CLM_STAT_CD IN ('10', '20', '40', '80', '90')),
    CONSTRAINT CK_CLM_AMT CHECK (TOTAL_CLAIM_AMT > 0 AND (TOTAL_PAY_AMT IS NULL OR TOTAL_PAY_AMT >= 0))
);

CREATE INDEX IX_CLM_CONTRACT_NO ON TB_CLM (CONTRACT_NO);
CREATE INDEX IX_CLM_STAT_RPT_DT ON TB_CLM (CLM_STAT_CD, RPT_DT DESC);
CREATE INDEX IX_CLM_RPT_DT ON TB_CLM (RPT_DT DESC, CLM_NO DESC);

-- 담보별 청구·사정·지급 금액. 지급액 = min(max(사정 손해액 - 자기부담금, 0), 그 담보의 남은 가입금액)
CREATE TABLE TB_CLM_CVRG (
    CLM_NO          VARCHAR(30)    NOT NULL,
    CVRG_CD         VARCHAR(10)    NOT NULL,
    CLAIM_AMT       NUMERIC(15, 0) NOT NULL,
    ASSESSED_AMT    NUMERIC(15, 0),
    DEDUCTIBLE_AMT  NUMERIC(15, 0),
    PAY_AMT         NUMERIC(15, 0),
    CONSTRAINT PK_CLM_CVRG PRIMARY KEY (CLM_NO, CVRG_CD),
    CONSTRAINT FK_CLM_CVRG_CLM FOREIGN KEY (CLM_NO) REFERENCES TB_CLM (CLM_NO),
    CONSTRAINT CK_CLM_CVRG_AMT CHECK (CLAIM_AMT > 0 AND (ASSESSED_AMT IS NULL OR ASSESSED_AMT >= 0)
        AND (PAY_AMT IS NULL OR PAY_AMT >= 0))
);

-- 보상 상태 이력. 추가 전용. 같은 사고에서 같은 거래 UUID 는 한 번만 처리된다(재전송 판별).
CREATE TABLE TB_CLM_HIST (
    HIST_ID         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CLM_NO          VARCHAR(30)  NOT NULL,
    BEFORE_STAT_CD  VARCHAR(2),
    AFTER_STAT_CD   VARCHAR(2)   NOT NULL,
    EMP_ID          VARCHAR(64),
    MEMO            VARCHAR(500),
    GLOBAL_TX_ID    VARCHAR(64)  NOT NULL,
    CHG_DT          TIMESTAMP    NOT NULL,
    CONSTRAINT PK_CLM_HIST PRIMARY KEY (HIST_ID),
    CONSTRAINT FK_CLM_HIST_CLM FOREIGN KEY (CLM_NO) REFERENCES TB_CLM (CLM_NO),
    CONSTRAINT UK_CLM_HIST_TX UNIQUE (CLM_NO, GLOBAL_TX_ID)
);
