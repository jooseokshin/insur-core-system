-- 필수 요율 계수 정책: 보험종목별로 보험료 산출/청약에서 반드시 입력해야 하는 요율 계수 종류를 정한다.
-- 정책도 적용 기간(EFF_FROM ~ EFF_TO, 양 끝 포함, EFF_TO 가 NULL 이면 현재까지 유효)으로 이력을 관리하며 보험시기에 적용되는 행을 쓴다.
-- 필수가 아닌 계수는 입력하지 않으면 적용하지 않는다(계수 1.0). 행이 없는 계수 종류도 필수가 아니다.
CREATE TABLE TB_PRM_FACTOR_POLICY (
    POLICY_ID    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    INSR_CLS_CD  VARCHAR(2)  NOT NULL,
    FACTOR_TYPE  VARCHAR(20) NOT NULL,
    REQUIRED_YN  BOOLEAN     NOT NULL,
    EFF_FROM     DATE        NOT NULL,
    EFF_TO       DATE,
    CONSTRAINT PK_PRM_FACTOR_POLICY PRIMARY KEY (POLICY_ID),
    CONSTRAINT UK_PRM_FACTOR_POLICY UNIQUE (INSR_CLS_CD, FACTOR_TYPE, EFF_FROM),
    CONSTRAINT CK_PRM_FACTOR_POLICY_PERIOD CHECK (EFF_TO IS NULL OR EFF_TO >= EFF_FROM)
);

CREATE FUNCTION FN_PRM_POLICY_NO_OVERLAP() RETURNS trigger AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM TB_PRM_FACTOR_POLICY p
                WHERE p.INSR_CLS_CD = NEW.INSR_CLS_CD AND p.FACTOR_TYPE = NEW.FACTOR_TYPE
                  AND p.POLICY_ID IS DISTINCT FROM NEW.POLICY_ID
                  AND daterange(p.EFF_FROM, p.EFF_TO, '[]') && daterange(NEW.EFF_FROM, NEW.EFF_TO, '[]')) THEN
        RAISE EXCEPTION '필수 계수 정책 적용 기간이 겹칩니다: 보험종목=%, 계수=%, 시작일=%', NEW.INSR_CLS_CD, NEW.FACTOR_TYPE, NEW.EFF_FROM
            USING ERRCODE = '23P01';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER TRG_PRM_POLICY_NO_OVERLAP BEFORE INSERT OR UPDATE ON TB_PRM_FACTOR_POLICY
    FOR EACH ROW EXECUTE FUNCTION FN_PRM_POLICY_NO_OVERLAP();

