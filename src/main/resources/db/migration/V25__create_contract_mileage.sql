-- 계약별 마일리지 특약 (자동차 계약 1건에 1행)
CREATE TABLE TB_CTR_MILEAGE (
    CONTRACT_NO       VARCHAR(30)    NOT NULL,
    MIL_STAT_CD       VARCHAR(2)     NOT NULL,
    START_ODO_KM      INTEGER        NOT NULL,
    START_REG_DT      TIMESTAMP      NOT NULL,
    START_EMP_ID      VARCHAR(64),
    START_TX_ID       VARCHAR(64)    NOT NULL,
    END_ODO_KM        INTEGER,
    END_REG_DT        TIMESTAMP,
    END_EMP_ID        VARCHAR(64),
    END_TX_ID         VARCHAR(64),
    DRIVEN_KM         INTEGER,
    ANNUAL_KM         INTEGER,
    REFUND_RATE       NUMERIC(5, 4),
    REFUND_BASE_PREM  NUMERIC(15, 0),
    REFUND_AMT        NUMERIC(15, 0),
    CONSTRAINT PK_CTR_MILEAGE PRIMARY KEY (CONTRACT_NO),
    CONSTRAINT FK_CTR_MILEAGE_CONTRACT FOREIGN KEY (CONTRACT_NO) REFERENCES TB_CTR_LGD (CONTRACT_NO),
    CONSTRAINT UK_CTR_MILEAGE_START_TX UNIQUE (START_TX_ID),
    CONSTRAINT UK_CTR_MILEAGE_END_TX UNIQUE (END_TX_ID),
    CONSTRAINT CK_CTR_MILEAGE_STAT CHECK (MIL_STAT_CD IN ('10', '20')),
    CONSTRAINT CK_CTR_MILEAGE_ODO CHECK (START_ODO_KM >= 0 AND (END_ODO_KM IS NULL OR END_ODO_KM >= START_ODO_KM)),
    CONSTRAINT CK_CTR_MILEAGE_SETTLED CHECK (MIL_STAT_CD = '10' OR (END_ODO_KM IS NOT NULL AND REFUND_AMT IS NOT NULL))
);
COMMENT ON TABLE TB_CTR_MILEAGE IS '마일리지 특약. 자동차 계약의 시작·만기 주행거리와 환급 정산 결과 (계약 1건에 1행)';
COMMENT ON COLUMN TB_CTR_MILEAGE.CONTRACT_NO IS '증권번호 (TB_CTR_LGD, 자동차 계약만)';
COMMENT ON COLUMN TB_CTR_MILEAGE.MIL_STAT_CD IS '마일리지 상태코드 (10:시작 주행거리 등록, 20:정산 완료)';
COMMENT ON COLUMN TB_CTR_MILEAGE.START_ODO_KM IS '시작 주행거리 (계기판 누적 km)';
COMMENT ON COLUMN TB_CTR_MILEAGE.START_REG_DT IS '시작 주행거리 등록 일시';
COMMENT ON COLUMN TB_CTR_MILEAGE.START_EMP_ID IS '시작 등록 처리자 (사번 또는 채널 클라이언트 ID)';
COMMENT ON COLUMN TB_CTR_MILEAGE.START_TX_ID IS '시작 등록 거래 UUID (멱등성 키)';
COMMENT ON COLUMN TB_CTR_MILEAGE.END_ODO_KM IS '만기 주행거리 (계기판 누적 km). 정산 전 null';
COMMENT ON COLUMN TB_CTR_MILEAGE.END_REG_DT IS '만기 주행거리 등록(정산) 일시';
COMMENT ON COLUMN TB_CTR_MILEAGE.END_EMP_ID IS '정산 처리자 (사번 또는 채널 클라이언트 ID)';
COMMENT ON COLUMN TB_CTR_MILEAGE.END_TX_ID IS '정산 거래 UUID (멱등성 키)';
COMMENT ON COLUMN TB_CTR_MILEAGE.DRIVEN_KM IS '실제 주행거리 = 만기 − 시작 (km)';
COMMENT ON COLUMN TB_CTR_MILEAGE.ANNUAL_KM IS '1년 환산 주행거리 = 실제 주행거리 × 365 ÷ 보험기간 일수 (반올림, km). 환급률 구간을 찾는 값';
COMMENT ON COLUMN TB_CTR_MILEAGE.REFUND_RATE IS '적용 환급률 (구간이 없으면 0)';
COMMENT ON COLUMN TB_CTR_MILEAGE.REFUND_BASE_PREM IS '환급 기준 보험료 (정산 시점의 계약 총보험료, 원)';
COMMENT ON COLUMN TB_CTR_MILEAGE.REFUND_AMT IS '환급액 = 기준 보험료 × 환급률 (원 미만 버림, 원)';
