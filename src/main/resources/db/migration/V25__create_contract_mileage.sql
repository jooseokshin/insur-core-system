-- 자동차보험 마일리지 특약. 가입할 때(보험시기 무렵) 계기판 주행거리를 등록하고, 만기 무렵 다시 등록하면
-- 1년 기준으로 환산한 주행거리 구간에 따라 보험료 일부를 돌려준다. 채널계(사진 접수)나 직원 화면이 등록하고, 계산은 기간계가 한다.

-- 주행거리 구간별 환급률 (적용 기간별, 보험시기 기준으로 찾는다). 구간이 없는 거리는 환급 0.
-- 값은 개발용 예시이며 실제 상품의 환급률이 아니다. 바꿀 때는 기존 행의 EFF_TO 를 닫고 새 행을 넣는 마이그레이션을 쓴다.
CREATE TABLE TB_PRM_MILEAGE_RATE (
    RATE_ID      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    KM_FROM      INTEGER        NOT NULL,
    KM_TO        INTEGER        NOT NULL,
    REFUND_RATE  NUMERIC(5, 4)  NOT NULL,
    EFF_FROM     DATE           NOT NULL,
    EFF_TO       DATE,
    CONSTRAINT PK_PRM_MILEAGE_RATE PRIMARY KEY (RATE_ID),
    CONSTRAINT UK_PRM_MILEAGE_RATE UNIQUE (KM_FROM, EFF_FROM),
    CONSTRAINT CK_PRM_MILEAGE_RATE_RANGE CHECK (KM_FROM >= 0 AND KM_FROM <= KM_TO),
    CONSTRAINT CK_PRM_MILEAGE_RATE_VALUE CHECK (REFUND_RATE > 0 AND REFUND_RATE < 1),
    CONSTRAINT CK_PRM_MILEAGE_RATE_PERIOD CHECK (EFF_TO IS NULL OR EFF_TO >= EFF_FROM)
);
COMMENT ON TABLE TB_PRM_MILEAGE_RATE IS '마일리지 특약 환급률표. 1년 환산 주행거리 구간별 환급률 (적용 기간별, 개발용 예시 값)';
COMMENT ON COLUMN TB_PRM_MILEAGE_RATE.RATE_ID IS '환급률 일련번호';
COMMENT ON COLUMN TB_PRM_MILEAGE_RATE.KM_FROM IS '1년 환산 주행거리 구간 시작 (km, 포함)';
COMMENT ON COLUMN TB_PRM_MILEAGE_RATE.KM_TO IS '1년 환산 주행거리 구간 끝 (km, 포함)';
COMMENT ON COLUMN TB_PRM_MILEAGE_RATE.REFUND_RATE IS '환급률 (총보험료에 곱한다, 예 0.3200 = 32%)';
COMMENT ON COLUMN TB_PRM_MILEAGE_RATE.EFF_FROM IS '적용 시작일 (포함, 보험시기 기준으로 찾는다)';
COMMENT ON COLUMN TB_PRM_MILEAGE_RATE.EFF_TO IS '적용 종료일 (포함). null 이면 현재까지 유효';

