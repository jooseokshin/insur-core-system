    UPD_EMP_ID     VARCHAR(64),
    CONSTRAINT PK_FEP_INST PRIMARY KEY (INST_CD)
);
COMMENT ON TABLE TB_FEP_INST IS 'FEP 대외기관. 개시(SIGN_ON) 상태인 기관에만 업무 전문을 보낸다';
COMMENT ON COLUMN TB_FEP_INST.INST_CD IS '기관 코드 (KCIS:한국신용정보원, BANK:지급 은행 펌뱅킹)';
COMMENT ON COLUMN TB_FEP_INST.INST_NM IS '기관 이름';
COMMENT ON COLUMN TB_FEP_INST.SIGN_ON_YN IS '개시 여부. 종료(false)면 업무 전문을 보내지 않는다 (기관 정기 점검 시간 등)';
COMMENT ON COLUMN TB_FEP_INST.LAST_ECHO_DT IS '마지막 회선 확인(에코) 일시';
COMMENT ON COLUMN TB_FEP_INST.LAST_ECHO_OK IS '마지막 회선 확인 성공 여부';
COMMENT ON COLUMN TB_FEP_INST.UPD_DT IS '개시·종료 변경 일시';
COMMENT ON COLUMN TB_FEP_INST.UPD_EMP_ID IS '개시·종료 변경자';

