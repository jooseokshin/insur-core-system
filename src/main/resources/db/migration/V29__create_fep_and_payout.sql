COMMENT ON COLUMN TB_FEP_MSG_LOG.ERROR_MSG IS '오류 내용';

-- 지급 ----------------------------------------------------------------------------------------------
CREATE TABLE TB_PAY_OUT (
    PAYOUT_ID      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    SRC_TYPE       VARCHAR(10)    NOT NULL,
    SRC_NO         VARCHAR(30)    NOT NULL,
    CONTRACT_NO    VARCHAR(30)    NOT NULL,
    PAY_AMT        NUMERIC(15, 0) NOT NULL,
    BANK_CD        VARCHAR(3)     NOT NULL,
    ACCOUNT_ENC    VARCHAR(200)   NOT NULL,
    ACCOUNT_MASK   VARCHAR(30)    NOT NULL,
    HOLDER_NM      VARCHAR(50)    NOT NULL,
    STAT_CD        VARCHAR(2)     NOT NULL,
    TRACE_NO       VARCHAR(20)    NOT NULL,
    SEND_COUNT     INTEGER        NOT NULL DEFAULT 0,
    INQUIRY_COUNT  INTEGER        NOT NULL DEFAULT 0,
    NEXT_TRY_DT    TIMESTAMP      NOT NULL,
    RESULT_CD      VARCHAR(4),
    RESULT_MSG     VARCHAR(200),
    REQ_EMP_ID     VARCHAR(64),
    REQ_DT         TIMESTAMP      NOT NULL,
    SENT_DT        TIMESTAMP,
    DONE_DT        TIMESTAMP,
    GLOBAL_TX_ID   VARCHAR(64)    NOT NULL,
    CONSTRAINT PK_PAY_OUT PRIMARY KEY (PAYOUT_ID),
    CONSTRAINT FK_PAY_OUT_CONTRACT FOREIGN KEY (CONTRACT_NO) REFERENCES TB_CTR_LGD (CONTRACT_NO),
    CONSTRAINT UK_PAY_OUT_TRACE UNIQUE (TRACE_NO),
    CONSTRAINT UK_PAY_OUT_GLOBAL_TX_ID UNIQUE (GLOBAL_TX_ID),
    CONSTRAINT CK_PAY_OUT_SRC CHECK (SRC_TYPE IN ('CLAIM', 'MILEAGE')),
    CONSTRAINT CK_PAY_OUT_STAT CHECK (STAT_CD IN ('10', '30', '70', '80')),
    CONSTRAINT CK_PAY_OUT_AMT CHECK (PAY_AMT > 0)
);
-- 실패(80)하지 않은 지급은 원천(사고·마일리지)당 하나만. 실패하면 계좌를 고쳐 새로 요청할 수 있다
CREATE UNIQUE INDEX UK_PAY_OUT_ACTIVE_SRC ON TB_PAY_OUT (SRC_TYPE, SRC_NO) WHERE STAT_CD <> '80';
CREATE INDEX IX_PAY_OUT_DUE ON TB_PAY_OUT (STAT_CD, NEXT_TRY_DT);
CREATE INDEX IX_PAY_OUT_SENT_DT ON TB_PAY_OUT (SENT_DT);
COMMENT ON TABLE TB_PAY_OUT IS '지급 원장 (보험금·마일리지 환급금을 은행 펌뱅킹으로 이체). 원천당 실패하지 않은 지급은 하나';
COMMENT ON COLUMN TB_PAY_OUT.PAYOUT_ID IS '지급 일련번호';
COMMENT ON COLUMN TB_PAY_OUT.SRC_TYPE IS '지급 원천 (CLAIM:보험금, MILEAGE:마일리지 환급금)';
COMMENT ON COLUMN TB_PAY_OUT.SRC_NO IS '원천 번호 (보험금은 사고번호, 마일리지는 증권번호)';
COMMENT ON COLUMN TB_PAY_OUT.CONTRACT_NO IS '증권번호 (TB_CTR_LGD)';
COMMENT ON COLUMN TB_PAY_OUT.PAY_AMT IS '지급액 (원, 원천에서 가져온다: 사고 지급액 합계 또는 마일리지 환급액)';
COMMENT ON COLUMN TB_PAY_OUT.BANK_CD IS '받는 은행 코드 (3자리)';
COMMENT ON COLUMN TB_PAY_OUT.ACCOUNT_ENC IS '받는 계좌번호 (AES-GCM 암호문, Base64). 평문은 저장하지 않는다';
COMMENT ON COLUMN TB_PAY_OUT.ACCOUNT_MASK IS '마스킹한 계좌번호 (화면·대사용, 앞 3자리와 끝 3자리만)';
COMMENT ON COLUMN TB_PAY_OUT.HOLDER_NM IS '예금주 (예금주 조회로 은행 값과 같음을 확인한 이름)';
COMMENT ON COLUMN TB_PAY_OUT.STAT_CD IS '지급 상태 (10:이체 대기, 30:이체 완료, 70:결과 불명 - 결과 조회로 확인 중, 80:실패 - 계좌를 고쳐 다시 요청)';
COMMENT ON COLUMN TB_PAY_OUT.TRACE_NO IS '이체 거래고유번호 (요청할 때 정하고 재전송·결과 조회에도 같은 번호를 쓴다)';
COMMENT ON COLUMN TB_PAY_OUT.SEND_COUNT IS '이체 전문 전송 횟수';
COMMENT ON COLUMN TB_PAY_OUT.INQUIRY_COUNT IS '결과 조회 횟수';
COMMENT ON COLUMN TB_PAY_OUT.NEXT_TRY_DT IS '다음 처리(전송·결과 조회) 일시';
COMMENT ON COLUMN TB_PAY_OUT.RESULT_CD IS '마지막 은행 응답코드';
COMMENT ON COLUMN TB_PAY_OUT.RESULT_MSG IS '마지막 처리 결과 내용';
COMMENT ON COLUMN TB_PAY_OUT.REQ_EMP_ID IS '지급 요청자';
COMMENT ON COLUMN TB_PAY_OUT.REQ_DT IS '지급 요청 일시';
COMMENT ON COLUMN TB_PAY_OUT.SENT_DT IS '처음 이체 전문을 보낸 일시 (대사 기준일)';
COMMENT ON COLUMN TB_PAY_OUT.DONE_DT IS '완료·실패 확정 일시';
COMMENT ON COLUMN TB_PAY_OUT.GLOBAL_TX_ID IS '지급 요청 거래 UUID (멱등성 키)';

