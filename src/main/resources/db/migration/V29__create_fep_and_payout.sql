-- FEP(대외계 중계)와 보험금·환급금 펌뱅킹 지급, 은행 대사.
-- FEP 는 기관마다 따로 붙던 연계를 한곳으로 모아 개시·종료, 회선 상태 확인(에코), 장애 차단, 전문 로그를 공통으로 처리한다.
-- 지급은 은행 펌뱅킹으로 보낸다: 예금주 조회로 계좌를 확인하고, 이체를 보내고, 응답이 없으면(결과 불명) 다시 보내지 않고
-- 결과 조회로 확인한다(이중 지급 방지). 매일 은행 이체 내역과 우리 지급 원장을 맞춰 본다(대사, 배치 payoutReconJob).
-- 전문 배치와 응답코드는 이 프로젝트가 정한 것이며 실제 은행·기관 규격이 아니다.

-- FEP 기관 ---------------------------------------------------------------------------------------------
