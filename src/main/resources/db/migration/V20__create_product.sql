-- 상품과 상품별 담보 구성. 상품은 판매 기간이 있고, 담보는 주계약(MAIN, 반드시 가입)과 특약(RIDER, 선택)으로 나뉜다.
-- 담보별 가입금액 한도와 자기부담금(보상 때 손해액에서 빼는 금액)을 상품이 정한다. 보험료 요율은 계속 TB_PRM_RATE 가 맡는다.
CREATE TABLE TB_PRD (
    PRD_CD       VARCHAR(20)  NOT NULL,
    PRD_NM       VARCHAR(100) NOT NULL,
    INSR_CLS_CD  VARCHAR(2)   NOT NULL,
    PRD_DESC     VARCHAR(500),
    SALE_FROM    DATE         NOT NULL,
    SALE_TO      DATE,
    CONSTRAINT PK_PRD PRIMARY KEY (PRD_CD),
    CONSTRAINT CK_PRD_SALE_PERIOD CHECK (SALE_TO IS NULL OR SALE_TO >= SALE_FROM)
);

CREATE TABLE TB_PRD_CVRG (
    PRD_CD          VARCHAR(20)    NOT NULL,
    CVRG_CD         VARCHAR(10)    NOT NULL,
    CVRG_TYPE       VARCHAR(10)    NOT NULL,
    REQUIRED_YN     BOOLEAN        NOT NULL,
    MIN_ISRD_AMT    NUMERIC(15, 0) NOT NULL,
    MAX_ISRD_AMT    NUMERIC(15, 0) NOT NULL,
    DEDUCTIBLE_AMT  NUMERIC(15, 0) NOT NULL DEFAULT 0,
    SORT_ORD        INTEGER        NOT NULL,
    CONSTRAINT PK_PRD_CVRG PRIMARY KEY (PRD_CD, CVRG_CD),
    CONSTRAINT FK_PRD_CVRG_PRD FOREIGN KEY (PRD_CD) REFERENCES TB_PRD (PRD_CD),
    CONSTRAINT CK_PRD_CVRG_TYPE CHECK (CVRG_TYPE IN ('MAIN', 'RIDER')),
    -- 주계약은 항상 필수다
    CONSTRAINT CK_PRD_CVRG_MAIN_REQUIRED CHECK (CVRG_TYPE <> 'MAIN' OR REQUIRED_YN),
    CONSTRAINT CK_PRD_CVRG_AMT CHECK (MIN_ISRD_AMT > 0 AND MIN_ISRD_AMT <= MAX_ISRD_AMT),
    CONSTRAINT CK_PRD_CVRG_DEDUCTIBLE CHECK (DEDUCTIBLE_AMT >= 0)
);

