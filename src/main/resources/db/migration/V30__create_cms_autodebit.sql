-- 보험료 자동이체 (금융결제원 CMS 출금이체). 계약자(또는 예금주)의 출금 동의를 받아 계좌를 등록하고,
-- 출금일에 청약 보험료를 계좌에서 출금해 수납으로 기록한다. 결제원과는 파일로 주고받는다 (배치 cmsDebitJob):
--   등록 의뢰(EB11) → 등록 결과(EB12) → 출금 의뢰(EB21) → 출금 결과(EB22)
-- 파일 이름 EB21/EB22 는 공개 자료에서 확인한 출금 의뢰·결과 파일 이름이고, EB11/EB12 와 파일 배치·결과코드는
-- 이 프로젝트가 정한 것이며 실제 결제원 규격이 아니다.

-- 납입 방법에 자동이체(CMS)를 더한다 (직원 수납 API 는 CMS 를 받지 않는다. 배치만 쓴다)
ALTER TABLE TB_CTR_PAYMENT DROP CONSTRAINT CK_CTR_PAYMENT_METHOD;
ALTER TABLE TB_CTR_PAYMENT ADD CONSTRAINT CK_CTR_PAYMENT_METHOD CHECK (PAY_METHOD IN ('CASH', 'TRANSFER', 'CARD', 'CMS'));
COMMENT ON COLUMN TB_CTR_PAYMENT.PAY_METHOD IS '납부 방법 (CASH:현금, TRANSFER:계좌이체, CARD:카드, CMS:자동이체 출금 - 배치가 기록)';

-- 자동이체 등록 (출금 동의) ---------------------------------------------------------------------------
CREATE TABLE TB_CMS_MANDATE (
    MANDATE_ID      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONTRACT_NO     VARCHAR(30)   NOT NULL,
    PAYER_NM        VARCHAR(50)   NOT NULL,
    BANK_CD         VARCHAR(3)    NOT NULL,
    ACCOUNT_ENC     VARCHAR(200)  NOT NULL,
    ACCOUNT_MASK    VARCHAR(30)   NOT NULL,
    CONSENT_METHOD  VARCHAR(10)   NOT NULL,
    CONSENT_DT      TIMESTAMP     NOT NULL,
    CONSENT_REF     VARCHAR(100)  NOT NULL,
    STAT_CD         VARCHAR(2)    NOT NULL,
    RESULT_CD       VARCHAR(4),
    RESULT_MSG      VARCHAR(200),
    INHERITED_FROM  VARCHAR(30),
    REG_EMP_ID      VARCHAR(64),
    REG_DT          TIMESTAMP     NOT NULL,
    DONE_DT         TIMESTAMP,
    CANCEL_DT       TIMESTAMP,
    CANCEL_EMP_ID   VARCHAR(64),
    GLOBAL_TX_ID    VARCHAR(64)   NOT NULL,
    CONSTRAINT PK_CMS_MANDATE PRIMARY KEY (MANDATE_ID),
    CONSTRAINT FK_CMS_MANDATE_CONTRACT FOREIGN KEY (CONTRACT_NO) REFERENCES TB_CTR_LGD (CONTRACT_NO),
    CONSTRAINT UK_CMS_MANDATE_GLOBAL_TX_ID UNIQUE (GLOBAL_TX_ID),
    CONSTRAINT CK_CMS_MANDATE_STAT CHECK (STAT_CD IN ('10', '20', '30', '80', '90')),
    CONSTRAINT CK_CMS_MANDATE_CONSENT CHECK (CONSENT_METHOD IN ('PAPER', 'RECORDING', 'ARS', 'E_SIGN'))
);
-- 살아 있는(대기·의뢰·완료) 등록은 계약당 하나
CREATE UNIQUE INDEX UK_CMS_MANDATE_ACTIVE ON TB_CMS_MANDATE (CONTRACT_NO) WHERE STAT_CD IN ('10', '20', '30');
CREATE INDEX IX_CMS_MANDATE_STAT ON TB_CMS_MANDATE (STAT_CD);
COMMENT ON TABLE TB_CMS_MANDATE IS '보험료 자동이체 등록 (출금 동의). 계약당 살아 있는 등록은 하나';
COMMENT ON COLUMN TB_CMS_MANDATE.MANDATE_ID IS '자동이체 등록 일련번호';
COMMENT ON COLUMN TB_CMS_MANDATE.CONTRACT_NO IS '증권번호 (TB_CTR_LGD). 결제원 파일의 납부자번호로 쓴다';
COMMENT ON COLUMN TB_CMS_MANDATE.PAYER_NM IS '예금주 (출금 동의자, 등록할 때 예금주 조회로 은행 값과 같음을 확인)';
COMMENT ON COLUMN TB_CMS_MANDATE.BANK_CD IS '출금 은행 코드 (3자리)';
COMMENT ON COLUMN TB_CMS_MANDATE.ACCOUNT_ENC IS '출금 계좌번호 (AES-256-GCM 암호문, Base64)';
COMMENT ON COLUMN TB_CMS_MANDATE.ACCOUNT_MASK IS '마스킹한 출금 계좌번호';
COMMENT ON COLUMN TB_CMS_MANDATE.CONSENT_METHOD IS '출금 동의 방식 (PAPER:서면, RECORDING:전화 녹취, ARS:자동응답, E_SIGN:전자서명). 전자금융거래법 시행령이 정한 방법';
COMMENT ON COLUMN TB_CMS_MANDATE.CONSENT_DT IS '출금 동의 일시';
COMMENT ON COLUMN TB_CMS_MANDATE.CONSENT_REF IS '동의 증빙 관리번호 (신청서 번호, 녹취 파일 키 등. 증빙 원본은 별도 보관)';
COMMENT ON COLUMN TB_CMS_MANDATE.STAT_CD IS '등록 상태 (10:결제원 등록 대기, 20:등록 의뢰함, 30:등록 완료 - 출금 가능, 80:등록 불능, 90:해지)';
COMMENT ON COLUMN TB_CMS_MANDATE.RESULT_CD IS '결제원 등록 결과코드 (0000 정상)';
COMMENT ON COLUMN TB_CMS_MANDATE.RESULT_MSG IS '등록 결과 설명';
COMMENT ON COLUMN TB_CMS_MANDATE.INHERITED_FROM IS '갱신으로 자동이체를 이어받은 원 계약의 증권번호 (직접 등록이면 null)';
COMMENT ON COLUMN TB_CMS_MANDATE.REG_EMP_ID IS '등록 처리자 (사번 또는 채널 클라이언트 ID)';
COMMENT ON COLUMN TB_CMS_MANDATE.REG_DT IS '등록 일시';
COMMENT ON COLUMN TB_CMS_MANDATE.DONE_DT IS '결제원 등록 완료·불능 확정 일시';
COMMENT ON COLUMN TB_CMS_MANDATE.CANCEL_DT IS '해지 일시';
COMMENT ON COLUMN TB_CMS_MANDATE.CANCEL_EMP_ID IS '해지 처리자';
COMMENT ON COLUMN TB_CMS_MANDATE.GLOBAL_TX_ID IS '등록 거래 UUID (멱등성 키)';

-- 출금 의뢰 건 -------------------------------------------------------------------------------------
CREATE TABLE TB_CMS_DEBIT (
    DEBIT_ID          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    DEBIT_DT          DATE           NOT NULL,
    MANDATE_ID        BIGINT         NOT NULL,
    CONTRACT_NO       VARCHAR(30)    NOT NULL,
    AMOUNT            NUMERIC(15, 0) NOT NULL,
    ATTEMPT_NO        INTEGER        NOT NULL,
    STAT_CD           VARCHAR(2)     NOT NULL,
    RESULT_CD         VARCHAR(4),
    RESULT_MSG        VARCHAR(200),
    PAYMENT_ID        BIGINT,
    JOB_EXECUTION_ID  BIGINT         NOT NULL,
    CREATED_DT        TIMESTAMP      NOT NULL,
    DONE_DT           TIMESTAMP,
    CONSTRAINT PK_CMS_DEBIT PRIMARY KEY (DEBIT_ID),
    CONSTRAINT FK_CMS_DEBIT_MANDATE FOREIGN KEY (MANDATE_ID) REFERENCES TB_CMS_MANDATE (MANDATE_ID),
    CONSTRAINT FK_CMS_DEBIT_CONTRACT FOREIGN KEY (CONTRACT_NO) REFERENCES TB_CTR_LGD (CONTRACT_NO),
    CONSTRAINT FK_CMS_DEBIT_PAYMENT FOREIGN KEY (PAYMENT_ID) REFERENCES TB_CTR_PAYMENT (PAYMENT_ID),
    CONSTRAINT UK_CMS_DEBIT_DAY UNIQUE (CONTRACT_NO, DEBIT_DT),
    CONSTRAINT CK_CMS_DEBIT_STAT CHECK (STAT_CD IN ('10', '20', '30', '80')),
    CONSTRAINT CK_CMS_DEBIT_AMT CHECK (AMOUNT > 0)
);
CREATE INDEX IX_CMS_DEBIT_DT ON TB_CMS_DEBIT (DEBIT_DT, STAT_CD);
COMMENT ON TABLE TB_CMS_DEBIT IS '자동이체 출금 의뢰 건 (출금일·계약당 한 건). 성공하면 수납(TB_CTR_PAYMENT, CMS)을 남긴다';
COMMENT ON COLUMN TB_CMS_DEBIT.DEBIT_ID IS '출금 일련번호';
COMMENT ON COLUMN TB_CMS_DEBIT.DEBIT_DT IS '출금일';
COMMENT ON COLUMN TB_CMS_DEBIT.MANDATE_ID IS '자동이체 등록 일련번호 (TB_CMS_MANDATE)';
COMMENT ON COLUMN TB_CMS_DEBIT.CONTRACT_NO IS '증권번호 (TB_CTR_LGD)';
COMMENT ON COLUMN TB_CMS_DEBIT.AMOUNT IS '출금 의뢰 금액 (원, 의뢰 시점의 남은 보험료)';
COMMENT ON COLUMN TB_CMS_DEBIT.ATTEMPT_NO IS '출금 시도 차수 (1부터, 실패하면 다음 출금일에 최대 3차까지 재출금)';
COMMENT ON COLUMN TB_CMS_DEBIT.STAT_CD IS '출금 상태 (10:의뢰 대상, 20:의뢰함 - 결과 대기, 30:출금 성공, 80:출금 실패)';
COMMENT ON COLUMN TB_CMS_DEBIT.RESULT_CD IS '결제원 출금 결과코드 (0000 정상)';
COMMENT ON COLUMN TB_CMS_DEBIT.RESULT_MSG IS '출금 결과 설명';
COMMENT ON COLUMN TB_CMS_DEBIT.PAYMENT_ID IS '출금 성공으로 기록한 수납 일련번호 (TB_CTR_PAYMENT)';
COMMENT ON COLUMN TB_CMS_DEBIT.JOB_EXECUTION_ID IS '출금을 의뢰한 배치 실행 일련번호 (BATCH_JOB_EXECUTION)';
COMMENT ON COLUMN TB_CMS_DEBIT.CREATED_DT IS '의뢰 대상으로 고른 일시';
COMMENT ON COLUMN TB_CMS_DEBIT.DONE_DT IS '결과 반영 일시';

-- 결제원 파일 송수신 기록 ---------------------------------------------------------------------------
CREATE TABLE TB_CMS_FILE (
    FILE_ID           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    FILE_TYPE         VARCHAR(4)     NOT NULL,
    FILE_DT           DATE           NOT NULL,
    DIRECTION         VARCHAR(4)     NOT NULL,
    RECORD_COUNT      INTEGER        NOT NULL,
    TOTAL_AMT         NUMERIC(15, 0) NOT NULL,
    BYTES             INTEGER        NOT NULL,
    FILE_HASH         VARCHAR(64)    NOT NULL,
    JOB_EXECUTION_ID  BIGINT         NOT NULL,
    CREATED_DT        TIMESTAMP      NOT NULL,
    CONSTRAINT PK_CMS_FILE PRIMARY KEY (FILE_ID),
    CONSTRAINT CK_CMS_FILE_TYPE CHECK (FILE_TYPE IN ('EB11', 'EB12', 'EB21', 'EB22')),
    CONSTRAINT CK_CMS_FILE_DIRECTION CHECK (DIRECTION IN ('SEND', 'RECV'))
);
CREATE INDEX IX_CMS_FILE_DT ON TB_CMS_FILE (FILE_DT, FILE_TYPE);
COMMENT ON TABLE TB_CMS_FILE IS '결제원 CMS 파일 송수신 기록. 본문은 계좌번호가 있어 남기지 않고 건수·합계·해시만 남긴다';
COMMENT ON COLUMN TB_CMS_FILE.FILE_ID IS '파일 기록 일련번호';
COMMENT ON COLUMN TB_CMS_FILE.FILE_TYPE IS '파일 종류 (EB11:등록 의뢰, EB12:등록 결과, EB21:출금 의뢰, EB22:출금 결과)';
COMMENT ON COLUMN TB_CMS_FILE.FILE_DT IS '파일 기준일 (출금일)';
COMMENT ON COLUMN TB_CMS_FILE.DIRECTION IS '방향 (SEND:보냄, RECV:받음)';
COMMENT ON COLUMN TB_CMS_FILE.RECORD_COUNT IS '데이터 건수 (꼬리 레코드 건수와 같아야 받는다)';
COMMENT ON COLUMN TB_CMS_FILE.TOTAL_AMT IS '금액 합계 (원, 등록 파일은 0. 꼬리 레코드 합계와 같아야 받는다)';
COMMENT ON COLUMN TB_CMS_FILE.BYTES IS '파일 크기 (바이트)';
COMMENT ON COLUMN TB_CMS_FILE.FILE_HASH IS '파일 SHA-256';
COMMENT ON COLUMN TB_CMS_FILE.JOB_EXECUTION_ID IS '배치 실행 일련번호 (BATCH_JOB_EXECUTION)';
COMMENT ON COLUMN TB_CMS_FILE.CREATED_DT IS '송수신 일시';

