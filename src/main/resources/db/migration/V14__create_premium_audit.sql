-- 요율/요율 계수 관리 감사 이력: 누가 언제 어떤 요율/계수를 새로 만들거나 개정했는지 남긴다. 추가 전용 테이블.
-- (TARGET_TYPE, GLOBAL_TX_ID) 유니크는 같은 거래 UUID 의 재전송과 동시 요청을 한 건만 반영하게 하는 장치이기도 하다.
CREATE TABLE TB_PRM_AUDIT (
    AUDIT_ID      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    TARGET_TYPE   VARCHAR(10)  NOT NULL,
    TARGET_KEY    VARCHAR(100) NOT NULL,
    ACTION        VARCHAR(10)  NOT NULL,
    BEFORE_VAL    VARCHAR(50),
    AFTER_VAL     VARCHAR(50)  NOT NULL,
    EFF_FROM      DATE         NOT NULL,
    EMP_ID        VARCHAR(64),
    GLOBAL_TX_ID  VARCHAR(64)  NOT NULL,
    CHG_DT        TIMESTAMP    NOT NULL,
    CONSTRAINT PK_PRM_AUDIT PRIMARY KEY (AUDIT_ID),
    CONSTRAINT UK_PRM_AUDIT_TX UNIQUE (TARGET_TYPE, GLOBAL_TX_ID),
    CONSTRAINT CK_PRM_AUDIT_TARGET CHECK (TARGET_TYPE IN ('RATE', 'FACTOR')),
    CONSTRAINT CK_PRM_AUDIT_ACTION CHECK (ACTION IN ('CREATE', 'REVISE'))
);
