-- 보험료 요율 계수표. 담보별 기본 요율(TB_PRM_RATE)에 곱해지는 계수이며, 보험종목마다 쓰는 계수 종류가 다르다.
--   범위형(RANGE_FROM~RANGE_TO, 양 끝 포함): 운전자 연령처럼 숫자 구간으로 계수가 정해지는 경우
--   키형(FACTOR_KEY): 할인할증 등급, 건물 구조 등급처럼 코드로 계수가 정해지는 경우
-- 아래 시드 값은 개발/시연용 샘플 계수다. 실제 계수로 교체하려면 새 마이그레이션(V<n>)으로 수정한다.
CREATE TABLE TB_PRM_FACTOR (
    FACTOR_ID     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    INSR_CLS_CD   VARCHAR(2)     NOT NULL,
    FACTOR_TYPE   VARCHAR(20)    NOT NULL,
    FACTOR_KEY    VARCHAR(10),
    RANGE_FROM    INTEGER,
    RANGE_TO      INTEGER,
    FACTOR_NM     VARCHAR(50)    NOT NULL,
    FACTOR_VALUE  NUMERIC(6, 4)  NOT NULL,
    CONSTRAINT PK_PRM_FACTOR PRIMARY KEY (FACTOR_ID),
    CONSTRAINT CK_PRM_FACTOR_VALUE CHECK (FACTOR_VALUE > 0),
    CONSTRAINT CK_PRM_FACTOR_KIND CHECK (
        (FACTOR_KEY IS NOT NULL AND RANGE_FROM IS NULL AND RANGE_TO IS NULL)
        OR (FACTOR_KEY IS NULL AND RANGE_FROM IS NOT NULL AND RANGE_TO IS NOT NULL AND RANGE_FROM <= RANGE_TO))
);

CREATE INDEX IX_PRM_FACTOR_INSR_TYPE ON TB_PRM_FACTOR (INSR_CLS_CD, FACTOR_TYPE);

