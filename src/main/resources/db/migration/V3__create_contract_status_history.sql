-- 계약상태 변경 이력: 청약 접수(최초 상태)와 이후 모든 상태 변경을 한 건씩 남긴다. 수정/삭제하지 않는 추가 전용 테이블.
CREATE TABLE TB_CTR_STAT_HIST (
    HIST_ID         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONTRACT_NO     VARCHAR(30) NOT NULL,
    BEFORE_STAT_CD  VARCHAR(2),
    AFTER_STAT_CD   VARCHAR(2)  NOT NULL,
    EMP_ID          VARCHAR(64),
    GLOBAL_TX_ID    VARCHAR(64) NOT NULL,
    CHG_DT          TIMESTAMP   NOT NULL,
    CONSTRAINT PK_CTR_STAT_HIST PRIMARY KEY (HIST_ID),
    CONSTRAINT FK_CTR_STAT_HIST_CONTRACT FOREIGN KEY (CONTRACT_NO) REFERENCES TB_CTR_LGD (CONTRACT_NO)
);

CREATE INDEX IX_CTR_STAT_HIST_CONTRACT_NO ON TB_CTR_STAT_HIST (CONTRACT_NO, HIST_ID);
