-- 계약 납입(수납) 내역: 청약 상태의 계약에 보험료를 나누어 낼 수 있고, 합계가 총보험료에 이르면 승인(유효)할 수 있다. 추가 전용 테이블.
CREATE TABLE TB_CTR_PAYMENT (
    PAYMENT_ID    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONTRACT_NO   VARCHAR(30)    NOT NULL,
    PAY_AMT       NUMERIC(15, 0) NOT NULL,
    PAY_METHOD    VARCHAR(10)    NOT NULL,
    EMP_ID        VARCHAR(64),
    GLOBAL_TX_ID  VARCHAR(64)    NOT NULL,
    PAID_DT       TIMESTAMP      NOT NULL,
    CONSTRAINT PK_CTR_PAYMENT PRIMARY KEY (PAYMENT_ID),
    CONSTRAINT FK_CTR_PAYMENT_CONTRACT FOREIGN KEY (CONTRACT_NO) REFERENCES TB_CTR_LGD (CONTRACT_NO),
    CONSTRAINT UK_CTR_PAYMENT_GLOBAL_TX_ID UNIQUE (GLOBAL_TX_ID),
    CONSTRAINT CK_CTR_PAYMENT_AMT CHECK (PAY_AMT > 0),
    CONSTRAINT CK_CTR_PAYMENT_METHOD CHECK (PAY_METHOD IN ('CASH', 'TRANSFER', 'CARD'))
);

CREATE INDEX IX_CTR_PAYMENT_CONTRACT_NO ON TB_CTR_PAYMENT (CONTRACT_NO, PAYMENT_ID);
