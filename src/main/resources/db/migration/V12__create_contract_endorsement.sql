-- 계약 변경(배서) 이력: 계약자/피보험자를 바꿀 때 바뀐 항목마다 한 건씩 변경 전/후 값을 남긴다. 추가 전용 테이블.
CREATE TABLE TB_CTR_ENDORSE (
    ENDORSE_ID    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONTRACT_NO   VARCHAR(30)  NOT NULL,
    FIELD_NM      VARCHAR(30)  NOT NULL,
    BEFORE_VAL    VARCHAR(100),
    AFTER_VAL     VARCHAR(100),
    EMP_ID        VARCHAR(64),
    GLOBAL_TX_ID  VARCHAR(64)  NOT NULL,
    CHG_DT        TIMESTAMP    NOT NULL,
    CONSTRAINT PK_CTR_ENDORSE PRIMARY KEY (ENDORSE_ID),
    CONSTRAINT FK_CTR_ENDORSE_CONTRACT FOREIGN KEY (CONTRACT_NO) REFERENCES TB_CTR_LGD (CONTRACT_NO)
);

CREATE INDEX IX_CTR_ENDORSE_CONTRACT_NO ON TB_CTR_ENDORSE (CONTRACT_NO, ENDORSE_ID);
