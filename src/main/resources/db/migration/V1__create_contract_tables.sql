-- 계약 원장
CREATE TABLE TB_CTR_LGD (
    CONTRACT_NO      VARCHAR(30)    NOT NULL,
    APPL_NO          VARCHAR(30)    NOT NULL,
    INSR_CLS_CD      VARCHAR(2)     NOT NULL,
    CTR_STAT_CD      VARCHAR(2)     NOT NULL,
    START_DATE       DATE           NOT NULL,
    END_DATE         DATE           NOT NULL,
    POLICYHOLDER_ID  VARCHAR(20)    NOT NULL,
    INSURED_ID       VARCHAR(20)    NOT NULL,
    TOTAL_PREMIUM    NUMERIC(15, 0) NOT NULL,
    SYS_REG_DT       TIMESTAMP      NOT NULL,
    CONSTRAINT PK_CTR_LGD PRIMARY KEY (CONTRACT_NO),
    CONSTRAINT UK_CTR_LGD_APPL_NO UNIQUE (APPL_NO)
);

-- 계약 담보
CREATE TABLE TB_CTR_CVRG (
    ID           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONTRACT_NO  VARCHAR(30)    NOT NULL,
    CVRG_CD      VARCHAR(10)    NOT NULL,
    ISRD_AMT     NUMERIC(15, 0) NOT NULL,
    PREM         NUMERIC(15, 0) NOT NULL,
    CONSTRAINT PK_CTR_CVRG PRIMARY KEY (ID),
    CONSTRAINT FK_CTR_CVRG_CONTRACT FOREIGN KEY (CONTRACT_NO) REFERENCES TB_CTR_LGD (CONTRACT_NO)
);

CREATE INDEX IX_CTR_CVRG_CONTRACT_NO ON TB_CTR_CVRG (CONTRACT_NO);

-- 채번 관리 (번호유형 + 상품구분 + 연도별 최종 일련번호)
CREATE TABLE TB_CMN_SEQ (
    SEQ_TYPE  VARCHAR(10) NOT NULL,
    PROD_CD   VARCHAR(10) NOT NULL,
    SEQ_YEAR  VARCHAR(4)  NOT NULL,
    LAST_NO   BIGINT      NOT NULL,
    CONSTRAINT PK_CMN_SEQ PRIMARY KEY (SEQ_TYPE, PROD_CD, SEQ_YEAR)
);
