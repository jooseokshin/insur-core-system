-- 담보별 보험료 요율표. 연 요율(가입금액 대비)이며 보험기간 일수에 비례해 보험료를 계산한다.
-- 아래 시드 값은 개발/시연용 샘플 요율이다. 실제 요율표로 교체하려면 새 마이그레이션(V<n>)으로 UPDATE/INSERT 한다.
CREATE TABLE TB_PRM_RATE (
    RATE_ID      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    INSR_CLS_CD  VARCHAR(2)    NOT NULL,
    CVRG_CD      VARCHAR(10)   NOT NULL,
    CVRG_NM      VARCHAR(50)   NOT NULL,
    ANNUAL_RATE  NUMERIC(10, 6) NOT NULL,
    CONSTRAINT PK_PRM_RATE PRIMARY KEY (RATE_ID),
    CONSTRAINT UK_PRM_RATE UNIQUE (INSR_CLS_CD, CVRG_CD),
    CONSTRAINT CK_PRM_RATE_POSITIVE CHECK (ANNUAL_RATE > 0)
);

