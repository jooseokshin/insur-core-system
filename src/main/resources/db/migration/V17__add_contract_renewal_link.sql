ALTER TABLE TB_CTR_LGD ADD COLUMN RENEWED_FROM VARCHAR(30);
ALTER TABLE TB_CTR_LGD ADD CONSTRAINT FK_CTR_LGD_RENEWED_FROM FOREIGN KEY (RENEWED_FROM) REFERENCES TB_CTR_LGD (CONTRACT_NO);

