COMMENT ON COLUMN BATCH_JOB_EXECUTION_PARAMS.PARAMETER_VALUE IS '파라미터 값';
COMMENT ON COLUMN BATCH_JOB_EXECUTION_PARAMS.IDENTIFYING IS '인스턴스를 구분하는 파라미터인지 (Y/N)';

